/**
 * 种子数据（seed data）
 *
 * 目的：在爬虫与 SQLite 就绪前，用硬编码数据打通后端查询接口，
 * 使前端可以据此开发搜索、筛选、标记、排课等功能。
 *
 * 注意：
 * - 字段结构必须与 docs/DESIGN.md §2.1 数据模型保持一致。
 * - 本文件为临时过渡方案，待爬虫 + SQLite 接入后替换。
 * - 数据由 scripts/convert_seed.py 从爬虫解析结果转换而来，
 *   挑选了覆盖多种场景的代表性样本（通识/专业、必修/选修、
 *   连续/不连续/单双周、单段/多段、无时间信息）。
 */

export interface SeedSchedule {
  /** 星期几（1=周一 … 7=周日） */
  day: number;
  /** 节次区间起点（1–14，含端点） */
  start: number;
  /** 节次区间终点（1–14，含端点） */
  end: number;
  /** 该时间段的上课地点 */
  location: string;
}

export interface SeedClass {
  /** 教学班代码，唯一，默认排序依据 */
  classCode: string;
  /** 课程代码（与大纲 id 无关） */
  courseCode: string;
  /** 课程名称 */
  courseName: string;
  /** 总学时 */
  totalHours: number;
  /** 学分 */
  credits: number;
  /** 授课教师 */
  teacher: string;
  /** 上课时间（多段） */
  schedule: SeedSchedule[];
  /** 实际开课周（可能不连续、可能单/双周） */
  weeks: number[];
  /** 培养层次 */
  level: string;
  /** 课程类型（仅筛选） */
  courseType: string;
  /** 课程性质（仅筛选） */
  courseNature: string;
  /** 开课部门（仅筛选） */
  department: string;
  /** 教学组成 */
  teachingComposition: string;
  /** 备注 */
  remark: string;
  /** 课程大纲 id 参数（用于拼接链接，0 表示待爬虫补充） */
  syllabusId: number;
}

